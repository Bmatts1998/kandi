"use strict";

// Safety buddy check-in. Not an emergency service.
// Tables use the safety_ prefix so they won't collide with Find My Crew (crew_) work.

const GRACE_MINUTES_DEFAULT = 15;
const MORNING_HOUR = 8;
const DEFAULT_TZ = "America/Denver";
const MAX_BUDDIES = 20;
const MAX_NOTE = 140;
const INTERVALS = [30, 60, 120, 180];
const DISCLAIMER = "Safety check is not an emergency service. If you or someone else is in danger, call 911.";

function nowIso(ms) {
  return new Date(ms != null ? ms : Date.now()).toISOString();
}

function toMs(v) {
  if (v == null || v === "") return 0;
  if (typeof v === "number" && Number.isFinite(v)) return v;
  let s = String(v).trim();
  if (!s.includes("T")) s = s.replace(" ", "T");
  if (/[+-]\d\d$/.test(s)) s += ":00";
  if (!/(Z|[+-]\d\d:?\d\d)$/.test(s)) s += "Z";
  const t = Date.parse(s);
  return Number.isFinite(t) ? t : 0;
}

function isPg(db) {
  return db && db.driver === "postgres";
}

function validTimeZone(tz) {
  const zone = String(tz || "").trim() || DEFAULT_TZ;
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: zone }).format(new Date());
    return zone;
  } catch (_) {
    return DEFAULT_TZ;
  }
}

function zonedParts(ms, timeZone) {
  const parts = {};
  const fmt = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  });
  for (const p of fmt.formatToParts(new Date(ms))) {
    if (p.type !== "literal") parts[p.type] = p.value;
  }
  return {
    year: Number(parts.year),
    month: Number(parts.month),
    day: Number(parts.day),
    hour: Number(parts.hour),
    minute: Number(parts.minute),
    second: Number(parts.second),
  };
}

function zonedTimeToUtcMs(year, month, day, hour, minute, timeZone) {
  let guess = Date.UTC(year, month - 1, day, hour, minute, 0);
  for (let i = 0; i < 4; i++) {
    const p = zonedParts(guess, timeZone);
    const got = Date.UTC(p.year, p.month - 1, p.day, p.hour, p.minute, 0);
    const want = Date.UTC(year, month - 1, day, hour, minute, 0);
    const delta = want - got;
    if (delta === 0) break;
    guess += delta;
  }
  return guess;
}

function addCalendarDays(year, month, day, days) {
  const dt = new Date(Date.UTC(year, month - 1, day + days));
  return { year: dt.getUTCFullYear(), month: dt.getUTCMonth() + 1, day: dt.getUTCDate() };
}

// A check started before 8am local ends at 8am that morning; otherwise it ends at 8am the next morning.
function nextMorningEnd(startMs, timeZone) {
  const tz = validTimeZone(timeZone);
  const p = zonedParts(startMs, tz);
  let ymd = { year: p.year, month: p.month, day: p.day };
  if (p.hour >= MORNING_HOUR) ymd = addCalendarDays(ymd.year, ymd.month, ymd.day, 1);
  return zonedTimeToUtcMs(ymd.year, ymd.month, ymd.day, MORNING_HOUR, 0, tz);
}

function clipNote(s) {
  return String(s == null ? "" : s).replace(/\s+/g, " ").trim().slice(0, MAX_NOTE);
}

function parseCoords(lat, lng) {
  if (lat == null || lng == null || lat === "" || lng === "") return { lat: null, lng: null };
  const la = Number(lat);
  const lo = Number(lng);
  if (!Number.isFinite(la) || !Number.isFinite(lo)) return { lat: null, lng: null };
  if (la < -90 || la > 90 || lo < -180 || lo > 180) return { lat: null, lng: null };
  return { lat: Math.round(la * 1e6) / 1e6, lng: Math.round(lo * 1e6) / 1e6 };
}

function mapsUrl(lat, lng) {
  if (lat == null || lng == null) return null;
  return "https://maps.google.com/?q=" + encodeURIComponent(lat + "," + lng);
}

function sendPushIfAvailable(userId, payload) {
  try {
    const push = require("./push");
    if (push && typeof push.sendToUser === "function") {
      Promise.resolve(push.sendToUser(userId, payload)).catch((err) => {
        console.error("safety push:", err.message || err);
      });
    }
  } catch (_) { /* push module is optional */ }
}

async function tableExists(db, name) {
  try {
    if (isPg(db)) {
      const row = await db.prepare(
        `SELECT 1 AS ok FROM information_schema.tables WHERE table_schema='public' AND table_name=?`
      ).get(name);
      return Boolean(row);
    }
    const row = await db.prepare(
      `SELECT 1 AS ok FROM sqlite_master WHERE type='table' AND name=?`
    ).get(name);
    return Boolean(row);
  } catch (_) {
    return false;
  }
}

async function ensureTables(db) {
  const pg = isPg(db);
  const idPk = pg
    ? "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    : "id INTEGER PRIMARY KEY AUTOINCREMENT";
  const nowDef = pg ? "DEFAULT (NOW()::text)" : "DEFAULT (datetime('now'))";
  const userRef = pg ? " REFERENCES users(id) ON DELETE CASCADE" : "";
  const checkRef = pg ? " REFERENCES safety_checks(id) ON DELETE CASCADE" : "";
  await db.exec(`CREATE TABLE IF NOT EXISTS safety_checks (
    ${idPk},
    user_id INTEGER NOT NULL${userRef},
    event_id TEXT DEFAULT '',
    event_key TEXT DEFAULT '',
    event_label TEXT DEFAULT '',
    schedule_kind TEXT NOT NULL,
    interval_minutes INTEGER,
    due_at TEXT NOT NULL,
    grace_minutes INTEGER NOT NULL DEFAULT 15,
    ends_at TEXT NOT NULL,
    timezone TEXT DEFAULT 'America/Denver',
    status TEXT NOT NULL DEFAULT 'active',
    location_note TEXT DEFAULT '',
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    share_gps INTEGER NOT NULL DEFAULT 0,
    last_checkin_at TEXT,
    missed_window TEXT,
    help_window TEXT,
    created_at TEXT ${nowDef},
    ended_at TEXT,
    ended_reason TEXT
  )`);
  await db.exec(`CREATE TABLE IF NOT EXISTS safety_buddies (
    check_id INTEGER NOT NULL${checkRef},
    user_id INTEGER NOT NULL${userRef},
    source TEXT DEFAULT '',
    created_at TEXT ${nowDef},
    PRIMARY KEY (check_id, user_id)
  )`);
  await db.exec(`CREATE TABLE IF NOT EXISTS safety_alerts (
    ${idPk},
    check_id INTEGER NOT NULL${checkRef},
    kind TEXT NOT NULL,
    to_user_id INTEGER NOT NULL${userRef},
    from_user_id INTEGER NOT NULL${userRef},
    window_key TEXT NOT NULL,
    body TEXT NOT NULL,
    location_note TEXT DEFAULT '',
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    event_label TEXT DEFAULT '',
    created_at TEXT ${nowDef},
    UNIQUE (check_id, kind, to_user_id, window_key)
  )`);
  await db.exec(`CREATE TABLE IF NOT EXISTS safety_notifications (
    ${idPk},
    user_id INTEGER NOT NULL${userRef},
    kind TEXT NOT NULL,
    from_id INTEGER,
    check_id INTEGER,
    alert_id INTEGER,
    text TEXT DEFAULT '',
    location_note TEXT DEFAULT '',
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    event_label TEXT DEFAULT '',
    created_at TEXT ${nowDef}
  )`);
  try { await db.exec("CREATE INDEX IF NOT EXISTS safety_checks_user ON safety_checks(user_id, status)"); } catch (_) {}
  try { await db.exec("CREATE INDEX IF NOT EXISTS safety_checks_due ON safety_checks(status, due_at)"); } catch (_) {}
  try { await db.exec("CREATE INDEX IF NOT EXISTS safety_buddies_user ON safety_buddies(user_id)"); } catch (_) {}
  try { await db.exec("CREATE INDEX IF NOT EXISTS safety_alerts_to ON safety_alerts(to_user_id, id)"); } catch (_) {}
  try { await db.exec("CREATE INDEX IF NOT EXISTS safety_notifications_user ON safety_notifications(user_id, id)"); } catch (_) {}
}

function showCrewApi() {
  try { return require("./show-crew"); } catch (_) { return null; }
}

// Reuses Find My Crew membership when a show is attached and that crew window is open.
async function listShowCrewMemberIds(db, userId, eventId, blockedSet) {
  const api = showCrewApi();
  if (!api || !eventId || typeof api.crewMemberIds !== "function") return [];
  try {
    const ids = await api.crewMemberIds(db, userId, eventId, blockedSet ? { blockedSet } : {});
    return (ids || []).map(Number).filter((id) => id && id !== Number(userId));
  } catch (err) {
    console.error("safety show-crew members:", err.message || err);
    return [];
  }
}

// Reuses Find My Crew's last note and opt-in GPS for the show, when the window is open.
async function probeCrewLocation(db, userId, eventId) {
  const api = showCrewApi();
  if (!api || !eventId) return null;
  try {
    let note = "";
    let lat = null;
    let lng = null;
    if (typeof api.getCrewMemberStatus === "function") {
      const status = await api.getCrewMemberStatus(db, userId, userId, eventId);
      if (status && status.member) {
        note = clipNote(status.note || (status.location && status.location.note) || "");
        if (status.location && status.location.lat != null) {
          lat = Number(status.location.lat);
          lng = status.location.lng == null ? null : Number(status.location.lng);
        }
      }
    }
    if (lat == null && typeof api.getLastLocation === "function") {
      const loc = await api.getLastLocation(db, userId, eventId);
      if (loc) {
        if (!note) note = clipNote(loc.note || "");
        if (loc.lat != null) { lat = Number(loc.lat); lng = loc.lng == null ? null : Number(loc.lng); }
      }
    }
    if (note || lat != null) return { note, lat, lng, source: "crew" };
  } catch (err) {
    console.error("safety show-crew location:", err.message || err);
  }
  return null;
}

async function resolveLastLocation(db, userId, eventId, fallback) {
  const crew = await probeCrewLocation(db, userId, eventId);
  if (crew && (crew.note || crew.lat != null)) return crew;

  const live = await db.prepare(`SELECT meetup_spot, event_id FROM live WHERE user_id=?`).get(userId);
  if (live && live.meetup_spot && (!eventId || String(live.event_id) === String(eventId) || !live.event_id)) {
    return { note: clipNote(live.meetup_spot), lat: null, lng: null, source: "live" };
  }

  if (eventId) {
    const going = await db.prepare(
      `SELECT meet_note FROM event_going WHERE user_id=? AND (event_id=? OR event_key=?)`
    ).get(userId, eventId, eventId);
    if (going && going.meet_note) {
      return { note: clipNote(going.meet_note), lat: null, lng: null, source: "rsvp" };
    }
  }

  if (fallback && (fallback.note || fallback.lat != null)) {
    return {
      note: clipNote(fallback.note || ""),
      lat: fallback.lat == null ? null : fallback.lat,
      lng: fallback.lng == null ? null : fallback.lng,
      source: "check",
    };
  }
  return { note: "", lat: null, lng: null, source: null };
}

async function eligibleBuddyMap(db, userId, eventId, blockedSet) {
  const me = Number(userId);
  const blocked = blockedSet || new Set();
  const map = new Map(); // id -> { sources: Set }

  function add(id, source) {
    const n = Number(id);
    if (!n || n === me || blocked.has(n)) return;
    let rec = map.get(n);
    if (!rec) { rec = { sources: new Set() }; map.set(n, rec); }
    if (source) rec.sources.add(source);
  }

  const matches = await db.prepare(`SELECT a_id, b_id, match_kind FROM matches WHERE a_id=? OR b_id=?`).all(me, me);
  for (const m of matches) {
    const other = Number(m.a_id) === me ? Number(m.b_id) : Number(m.a_id);
    add(other, "match");
    if (String(m.match_kind || "") === "friend") add(other, "friend");
  }

  const follows = await db.prepare(`
    SELECT following_id AS id FROM follows WHERE follower_id=?
    UNION
    SELECT follower_id AS id FROM follows WHERE following_id=?
  `).all(me, me);
  for (const r of follows) add(r.id, "friend");

  try {
    const crewMates = await db.prepare(`
      SELECT m.user_id AS id
      FROM crew_members me
      JOIN crew_members m ON m.crew_id=me.crew_id AND m.user_id!=me.user_id
      WHERE me.user_id=?
    `).all(me);
    for (const r of crewMates) add(r.id, "crew");
  } catch (_) { /* standing crews may be missing in a stripped test db */ }

  const showCrewMembers = await listShowCrewMemberIds(db, me, eventId, blocked);
  for (const id of showCrewMembers) add(id, "crew");

  return map;
}

async function isEligibleBuddy(db, ownerId, buddyId, eventId, blocked) {
  if (Number(ownerId) === Number(buddyId)) return false;
  if (blocked && (blocked.has(Number(buddyId)) || blocked.has(Number(ownerId)))) return false;
  const map = await eligibleBuddyMap(db, ownerId, eventId, blocked);
  return map.has(Number(buddyId));
}

function primarySource(sources) {
  if (sources.has("crew")) return "crew";
  if (sources.has("friend")) return "friend";
  if (sources.has("match")) return "match";
  return "match";
}

async function listEligibleBuddies(db, userId, eventId, blockedSet, publicUser) {
  const map = await eligibleBuddyMap(db, userId, eventId, blockedSet);
  const people = [];
  for (const [id, rec] of map) {
    const u = await db.prepare(`SELECT * FROM users WHERE id=?`).get(id);
    if (!u) continue;
    const sources = Array.from(rec.sources);
    const shaped = publicUser ? publicUser(u) : { id: u.id, name: u.name, username: u.username };
    people.push({
      id: Number(shaped.id || u.id),
      name: shaped.name,
      username: shaped.username,
      photos: (shaped.photos || []).slice(0, 1),
      source: primarySource(rec.sources),
      sources,
    });
  }
  people.sort((a, b) => String(a.name || "").localeCompare(String(b.name || "")));
  return people;
}

async function eventLabelFor(db, eventId) {
  if (!eventId) return "";
  const ev = await db.prepare(`SELECT * FROM events WHERE id=? OR event_key=?`).get(eventId, eventId);
  if (!ev) return String(eventId);
  const bits = [ev.name, ev.date_label || ev.date, ev.venue, ev.city].filter(Boolean);
  return bits[0] ? String(ev.name) + (ev.date_label ? " · " + ev.date_label : "") : String(eventId);
}

function locationSnippet(loc) {
  const bits = [];
  if (loc && loc.note) bits.push(loc.note);
  if (loc && loc.lat != null && loc.lng != null) bits.push("GPS " + loc.lat + ", " + loc.lng);
  return bits.join(" · ");
}

function shapeCheck(row, buddies, extra) {
  if (!row) return null;
  const shareGps = Number(row.share_gps) === 1;
  return {
    id: Number(row.id),
    userId: Number(row.user_id),
    eventId: row.event_id || "",
    eventKey: row.event_key || "",
    eventLabel: row.event_label || "",
    scheduleKind: row.schedule_kind,
    intervalMinutes: row.interval_minutes == null ? null : Number(row.interval_minutes),
    dueAt: row.due_at,
    graceMinutes: Number(row.grace_minutes || GRACE_MINUTES_DEFAULT),
    endsAt: row.ends_at,
    timezone: row.timezone || DEFAULT_TZ,
    status: row.status,
    locationNote: row.location_note || "",
    lat: shareGps ? (row.lat == null ? null : Number(row.lat)) : null,
    lng: shareGps ? (row.lng == null ? null : Number(row.lng)) : null,
    shareGps,
    lastCheckinAt: row.last_checkin_at || null,
    createdAt: row.created_at,
    endedAt: row.ended_at || null,
    endedReason: row.ended_reason || null,
    buddies: buddies || [],
    disclaimer: DISCLAIMER,
    ...(extra || {}),
  };
}

async function loadBuddies(db, checkId, publicUser, blocked) {
  const rows = await db.prepare(`
    SELECT b.source, u.* FROM safety_buddies b
    JOIN users u ON u.id=b.user_id
    WHERE b.check_id=?
  `).all(checkId);
  return rows
    .filter((u) => !blocked || !blocked.has(Number(u.id)))
    .map((u) => {
      const shaped = publicUser ? publicUser(u) : { id: u.id, name: u.name, username: u.username, photos: [] };
      return {
        id: Number(shaped.id || u.id),
        name: shaped.name,
        username: shaped.username,
        photos: (shaped.photos || []).slice(0, 1),
        source: u.source || "",
      };
    });
}

